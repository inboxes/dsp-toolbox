<#
.SYNOPSIS
  Writes THIRD_PARTY_NOTICES.md from third_party/LICENSES and the vcpkg copyright files of the shipped build.
.PARAMETER ShareDirs
  vcpkg_installed/<triplet>/share folders of the builds that go into the package.
#>
param(
    [Parameter(Mandatory)][string[]]$ShareDirs,
    [Parameter(Mandatory)][string]$OutFile,
    [string]$AsioSdkDir = ''
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

# Build-only or test-only packages don't ship. Anything not listed here must have a copyright file.
$skip = 'doctest', 'pkgconfig', 'vcpkg', 'vcpkg-cmake', 'vcpkg-cmake-config', 'man', 'doc', 'nlohmann_json', 'mysofa'

$packages = @{}
foreach ($share in $ShareDirs) {
    foreach ($dir in Get-ChildItem $share -Directory) {
        if ($skip -contains $dir.Name) { continue }
        $copyright = Join-Path $dir.FullName 'copyright'
        if (Test-Path $copyright) {
            $packages[$dir.Name] = $copyright
        } else {
            throw "No copyright file for the vcpkg package '$($dir.Name)'. Add it to the skip list only if it doesn't ship."
        }
    }
}

$out = New-Object System.Text.StringBuilder
function Add-Text([string]$text) { [void]$out.AppendLine($text) }
function Add-File([string]$heading, [string]$path) {
    Add-Text "## $heading"
    Add-Text ''
    Add-Text '```text'
    Add-Text ((Get-Content $path -Raw).TrimEnd())
    Add-Text '```'
    Add-Text ''
}

Add-Text '# Third-party notices'
Add-Text ''
Add-Text 'This file is generated by `tools/generate-notices.ps1`. Do not edit it by hand.'
Add-Text ''
Add-Text 'DSP Toolbox itself is licensed under GPL-3.0-only (see `LICENSE`, and `MODULE-EXCEPTION.md` for modules). It includes or uses the software and data below under their own licences.'
Add-Text ''
Add-Text '## ASIO'
Add-Text ''
Add-Text 'ASIO is a registered trademark of Steinberg Media Technologies GmbH.'
Add-Text ''
Add-Text 'This build uses the Steinberg ASIO SDK under its GPLv3 option. The SDK headers it was built from are in the source zip attached to each release.'
Add-Text ''
if ($AsioSdkDir) { Add-File 'Steinberg ASIO SDK licence' (Join-Path $AsioSdkDir 'LICENSE.txt') }
Add-Text '## Microsoft Visual C++ runtime'
Add-Text ''
Add-Text 'The VC++ runtime DLLs next to the executable are Microsoft redistributable files, covered by the Visual Studio licence terms.'
Add-Text ''
foreach ($name in ($packages.Keys | Sort-Object)) { Add-File $name $packages[$name] }

$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($OutFile, $out.ToString(), $utf8)
Write-Host "Wrote $OutFile with $($packages.Count) vcpkg packages: $(($packages.Keys | Sort-Object) -join ', ')"
