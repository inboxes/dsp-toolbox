#!/usr/bin/env python3
"""Generate the colormap lookup tables for dsptb::dsp (spec dsp-common.md §4.4).

Writes dsp_common/src/colormap_data.inl: 256-entry packed RGBA8 tables
(R | G<<8 | B<<16 | A<<24, A = 255) for Magma, Viridis and Inferno, sampled
from matplotlib's listed colormaps at t = i/255 and rounded as round(255*c).
Grey is linear (i, i, i) and is built in C++, so it is not in the .inl.

The output is deterministic for a given matplotlib version: no timestamps,
fixed formatting, and the matplotlib version is recorded in the header.
Re-running this script must regenerate the committed file byte-identically.

Dev-only tool; the C++ build never needs Python (the .inl is committed).
Requires: pip install -r modules/common/tools/requirements.txt
"""

import math
from pathlib import Path

import matplotlib

# (C++ table name, matplotlib colormap name)
MAPS = [
    ("kMagmaLut", "magma"),
    ("kViridisLut", "viridis"),
    ("kInfernoLut", "inferno"),
]

ENTRIES_PER_LINE = 8


def pack(r: int, g: int, b: int) -> int:
    # Spec §4.4 packing: R | G<<8 | B<<16 | A<<24 with A = 255, i.e. the bytes
    # in memory are R, G, B, A (DXGI_FORMAT_R8G8B8A8_UNORM / IM_COL32 order).
    return r | (g << 8) | (b << 16) | (255 << 24)


def cie_lightness(r: float, g: float, b: float) -> float:
    # CIE 1976 L* (D65) from unquantised sRGB floats in [0, 1]: linearise,
    # take relative luminance Y, then the L* cube-root curve. Mirrors the
    # conversion in tests/test_colormap.cpp.
    def linearise(c: float) -> float:
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    y = 0.2126 * linearise(r) + 0.7152 * linearise(g) + 0.0722 * linearise(b)
    delta = 6.0 / 29.0
    if y > delta**3:
        return 116.0 * y ** (1.0 / 3.0) - 16.0
    return (24389.0 / 27.0) * y


def assert_float_lightness_strictly_increasing(mpl_name: str, floats: list[tuple[float, float, float]]) -> None:
    # Maintainer ruling on issue #9: the strict L* criterion applies to the
    # unquantised float source, where it holds. It does NOT survive the
    # round(255*c) quantisation to RGBA8 (Viridis gains byte-identical
    # neighbours), so it is asserted here, on the floats, and the C++ test
    # asserts the quantisation-aware property of the committed tables.
    previous = cie_lightness(*floats[0])
    for i in range(1, len(floats)):
        current = cie_lightness(*floats[i])
        if not current > previous:
            raise SystemExit(
                f"{mpl_name}: unquantised L* not strictly increasing at entry {i}: "
                f"{previous:.6f} -> {current:.6f}"
            )
        previous = current


def table_lines(cpp_name: str, mpl_name: str) -> list[str]:
    cmap = matplotlib.colormaps[mpl_name]
    floats = []
    values = []
    for i in range(256):
        r, g, b, _alpha = cmap(i / 255.0)
        floats.append((r, g, b))
        # round() is round-half-even. That matches the issue's round(255*c)
        # only because no sample sits near a .5 boundary in 255*c — assert
        # that here (review suggestion on PR #23) instead of just claiming
        # it, so a future matplotlib version cannot silently change a table
        # entry through the rounding mode.
        for c in (r, g, b):
            scaled = 255.0 * c
            if abs(scaled - math.floor(scaled) - 0.5) <= 1e-6:
                raise SystemExit(
                    f"{mpl_name}[{i}]: channel value {c!r} sits on a .5 rounding "
                    "boundary in 255*c; round-half-even may diverge from round(255*c)"
                )
        values.append(pack(round(255 * r), round(255 * g), round(255 * b)))
    assert_float_lightness_strictly_increasing(mpl_name, floats)
    lines = [f"inline constexpr std::array<std::uint32_t, 256> {cpp_name} = {{"]
    for start in range(0, 256, ENTRIES_PER_LINE):
        chunk = ", ".join(f"0x{v:08X}u" for v in values[start : start + ENTRIES_PER_LINE])
        lines.append(f"    {chunk},")
    lines.append("};")
    return lines


def main() -> None:
    out_path = Path(__file__).resolve().parent.parent / "dsp_common" / "src" / "colormap_data.inl"
    lines = [
        "// Generated by modules/common/tools/gen_colormaps.py -- do not edit by hand.",
        "// Regenerate with: python modules/common/tools/gen_colormaps.py",
        "//",
        f"// Source: matplotlib {matplotlib.__version__} listed colormaps (Magma, Viridis,",
        "// Inferno), sampled at t = i/255, each channel rounded as round(255*c).",
        "// The Magma, Viridis and Inferno colormaps are released under CC0 by",
        "// Nathaniel J. Smith, Stefan van der Walt and Eric Firing (spec dsp-common.md",
        "// 4.4). Packing: R | G<<8 | B<<16 | A<<24 with A = 255.",
        "",
        "namespace dsptb::dsp::detail {",
        "",
    ]
    for cpp_name, mpl_name in MAPS:
        lines.extend(table_lines(cpp_name, mpl_name))
        lines.append("")
    lines.append("} // namespace dsptb::dsp::detail")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
